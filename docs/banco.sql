-- Esquema de referência. A aplicação executa a criação automaticamente em BancoDados.java.
CREATE TABLE IF NOT EXISTS fornecedor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    contato VARCHAR(100) NOT NULL DEFAULT '',
    telefone VARCHAR(30) NOT NULL DEFAULT '',
    email VARCHAR(120) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    preco DECIMAL(12,2) NOT NULL CHECK (preco >= 0),
    estoque_minimo INT NOT NULL CHECK (estoque_minimo >= 0),
    quantidade INT NOT NULL DEFAULT 0 CHECK (quantidade >= 0),
    fornecedor_id BIGINT NOT NULL REFERENCES fornecedor(id)
);

CREATE TABLE IF NOT EXISTS movimentacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL REFERENCES produto(id),
    tipo VARCHAR(7) NOT NULL CHECK (tipo IN ('ENTRADA', 'SAIDA')),
    quantidade INT NOT NULL CHECK (quantidade > 0),
    data TIMESTAMP NOT NULL,
    observacao VARCHAR(250) NOT NULL DEFAULT '',
    saldo_apos INT NOT NULL CHECK (saldo_apos >= 0)
);

CREATE INDEX IF NOT EXISTS idx_movimentacao_data ON movimentacao(data);
CREATE INDEX IF NOT EXISTS idx_movimentacao_produto ON movimentacao(produto_id);
